function t(key, vars) {
  const lang = getLanguage();
  let str = (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) ?? TRANSLATIONS.ru[key] ?? key;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      str = str.replace(`{${k}}`, vars[k]);
    });
  }
  return str;
}

function tMonths() {
  const lang = getLanguage();
  return TRANSLATIONS[lang]?.months || TRANSLATIONS.ru.months;
}

function tWeekdays() {
  const lang = getLanguage();
  return TRANSLATIONS[lang]?.weekdays || TRANSLATIONS.ru.weekdays;
}

function localeForLanguage(lang) {
  return { ru: 'ru-RU', en: 'en-GB', cs: 'cs-CZ' }[lang] || 'ru-RU';
}

function formatDate(dateStrOrObj) {
  const d = dateStrOrObj instanceof Date ? dateStrOrObj : new Date(dateStrOrObj);
  return d.toLocaleDateString(localeForLanguage(getLanguage()));
}

function formatDateTime(dateStrOrObj) {
  const d = dateStrOrObj instanceof Date ? dateStrOrObj : new Date(dateStrOrObj);
  return d.toLocaleString(localeForLanguage(getLanguage()));
}

