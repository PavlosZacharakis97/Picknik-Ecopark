function getCottageName(cottage) {
  const lang = getLanguage();
  if (lang === 'en' && cottage.name_en) return cottage.name_en;
  if (lang === 'cs' && cottage.name_cs) return cottage.name_cs;
  return cottage.name;
}

function getCottageDescription(cottage) {
  const lang = getLanguage();
  if (lang === 'en' && cottage.description_en) return cottage.description_en;
  if (lang === 'cs' && cottage.description_cs) return cottage.description_cs;
  return cottage.description;
}

